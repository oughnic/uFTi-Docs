#requires -Version 7
<#
.SYNOPSIS
  Writes the "Software components and licences" topic of each manual from the copied inventory (DEC-248).

.DESCRIPTION
  Reads content/components/<platform>.json (made by import-components.ps1) and writes one DITA reference
  topic for each device family, with the help identifier about.components:

      windows      -> content/platforms/windows/topics/software-components.dita
      android      -> content/platforms/android/topics/software-components.dita   (phone and tablet)
      ios          -> content/platforms/ios/topics/software-components.dita      (iPhone and iPad)
      maccatalyst  -> content/platforms/macos/topics/software-components.dita

  The topics are committed, so a build needs no run of this script. With -Check the script writes
  nothing and exits 1 when a topic differs from what the data would produce, so lint.ps1 can fail a
  topic that was edited by hand or a data file that was changed without a run of this script.
  Copyright 2026 Oughtibridge Ltd, Apache-2.0.

.PARAMETER Check
  Compare, do not write.

.PARAMETER Data
  The folder of the copied inventories. Default content/components.

.PARAMETER Root
  The content folder the topics go under. Default content/. The tests point it at a small tree.
#>
[CmdletBinding()]
param(
    [switch]$Check,
    [string]$Data,
    [string]$Root
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'UftiBuild.psm1') -Force
$repo = Get-UftiRepoRoot
if (-not $Data) { $Data = Join-Path $repo 'content/components' }
if (-not $Root) { $Root = Join-Path $repo 'content' }

$created = '2026-11-17'
$targets = @(
    @{ Data = 'windows';     Folder = 'platforms/windows'; Device = 'Windows' }
    @{ Data = 'android';     Folder = 'platforms/android'; Device = 'Android phones and tablets' }
    @{ Data = 'ios';         Folder = 'platforms/ios';     Device = 'the iPhone and iPad' }
    @{ Data = 'maccatalyst'; Folder = 'platforms/macos';   Device = 'the Mac' }
)

function X([string]$s) { if ($null -eq $s) { return '' }; [System.Security.SecurityElement]::Escape($s) }
function Link([string]$url, [string]$text) {
    if ($url -match '^https?://') { return '<xref href="{0}" scope="external" format="html">{1}</xref>' -f (X $url), (X $text) }
    return (X $text)
}
function LicenceCell($licence, [string]$name) {
    if ($null -eq $licence) { return 'Not recorded' }
    if ($licence -is [string]) { return (X $licence) }
    if ($licence.PSObject.Properties['expression'] -and $licence.expression) { return (X $licence.expression) }
    if ($licence.PSObject.Properties['url'] -and $licence.url) { return (Link $licence.url "Licence terms of $name") }
    if ($licence.PSObject.Properties['file'] -and $licence.file) { return 'The licence file that comes with the package' }
    return 'Not recorded'
}
function Row([string[]]$cells) { '            <row>' + (($cells | ForEach-Object { '<entry>' + $_ + '</entry>' }) -join '') + '</row>' }
function Table([string]$title, [string[]]$head, [string[]]$rows) {
    $cols = (1..$head.Count | ForEach-Object { '            <colspec colname="c{0}"/>' -f $_ }) -join "`n"
    @(
        '      <table frame="all" rowheader="firstcol">'
        '        <title>' + (X $title) + '</title>'
        '        <tgroup cols="' + $head.Count + '">'
        $cols
        '          <thead>'
        (Row ($head | ForEach-Object { X $_ }))
        '          </thead>'
        '          <tbody>'
        ($rows -join "`n")
        '          </tbody>'
        '        </tgroup>'
        '      </table>'
    ) -join "`n"
}

function New-Topic($j, [string]$device) {
    $pkgs = @($j.packages | Sort-Object { $_.id.ToLowerInvariant() })
    $copyrights = @($pkgs | ForEach-Object { $_.copyright } | Sort-Object -Unique)
    $sameCopyright = ($copyrights.Count -eq 1)
    $sb = [System.Text.StringBuilder]::new()
    $null = $sb.AppendLine('<?xml version="1.0" encoding="UTF-8"?>')
    $null = $sb.AppendLine('<!DOCTYPE reference PUBLIC "-//OASIS//DTD DITA Reference//EN" "reference.dtd">')
    $null = $sb.AppendLine('<!-- Generated by build/scripts/new-components-topics.ps1 from content/components. Do not edit by hand (DEC-248). -->')
    $null = $sb.AppendLine('<reference id="software-components" xml:lang="en-GB">')
    $null = $sb.AppendLine('  <title>Software components and licences</title>')
    $null = $sb.AppendLine('  <shortdesc>The parts of uFTi for ' + (X $device) + ' that other people made, and the licence of each.</shortdesc>')
    $null = $sb.AppendLine('  <prolog>')
    $null = $sb.AppendLine('    <critdates>')
    $null = $sb.AppendLine('      <created date="' + $created + '"/>')
    $null = $sb.AppendLine('    </critdates>')
    $null = $sb.AppendLine('    <metadata>')
    $null = $sb.AppendLine('      <audience type="user" experiencelevel="novice"/>')
    $null = $sb.AppendLine('      <category>Reference</category>')
    $null = $sb.AppendLine('      <keywords>')
    foreach ($k in 'software components', 'acknowledgements', 'fonts') { $null = $sb.AppendLine('        <keyword>' + $k + '</keyword>') }
    $null = $sb.AppendLine('      </keywords>')
    $null = $sb.AppendLine('    </metadata>')
    $null = $sb.AppendLine('    <resourceid appname="ufti" appid="about.components"/>')
    $null = $sb.AppendLine('  </prolog>')
    $null = $sb.AppendLine('  <refbody>')

    # about
    $null = $sb.AppendLine('    <section id="about-this-page">')
    $null = $sb.AppendLine('      <title>About this page</title>')
    $null = $sb.AppendLine('      <p>uFTi is made with parts that other people wrote. This page names the parts that are in uFTi for ' + (X $device) + '. It gives the version and the licence of each. A licence says what you may do with a part.</p>')
    $null = $sb.AppendLine('      <p>The list is made from the build of uFTi that this manual describes.</p>')
    $null = $sb.AppendLine('    </section>')

    # uFTi itself
    $null = $sb.AppendLine('    <section id="ufti-itself">')
    $null = $sb.AppendLine('      <title>uFTi</title>')
    $null = $sb.AppendLine('      <p>' + (X $j.app.copyright) + '</p>')
    $null = $sb.AppendLine('    </section>')

    # runtimes
    $rows = @($j.runtimes | ForEach-Object {
        Row @((X $_.name), (X $_.licence), (X $_.copyright), (Link $_.noticesUrl 'Notices of the parts that it uses'))
    })
    $null = $sb.AppendLine('    <section id="the-platform">')
    $null = $sb.AppendLine('      <title>What uFTi runs on</title>')
    $null = $sb.AppendLine('      <p>These make the app run. They come with their own notices about the parts that they use.</p>')
    $null = $sb.AppendLine((Table 'What uFTi runs on' @('Part', 'Licence', 'Copyright', 'Notices') $rows))
    $null = $sb.AppendLine('    </section>')

    # libraries
    $rows = @($pkgs | ForEach-Object {
        $cells = @((Link $_.projectUrl $_.id), (X $_.version), (LicenceCell $_.licence $_.id))
        if (-not $sameCopyright) { $cells += (X $_.copyright) }
        Row $cells
    })
    $head = @('Library', 'Version', 'Licence'); if (-not $sameCopyright) { $head += 'Copyright' }
    $null = $sb.AppendLine('    <section id="libraries">')
    $null = $sb.AppendLine('      <title>Libraries</title>')
    $null = $sb.AppendLine('      <p>uFTi for ' + (X $device) + ' uses ' + $pkgs.Count + ' libraries. Each name is a link to the page of the library.</p>')
    if ($sameCopyright) { $null = $sb.AppendLine('      <p>Every one of them states this copyright: ' + (X $copyrights[0]) + '</p>') }
    $null = $sb.AppendLine((Table 'Libraries in uFTi' $head $rows))
    $null = $sb.AppendLine('    </section>')

    # fonts
    $rows = @($j.fonts | ForEach-Object { Row @((Link $_.projectUrl $_.name), (X $_.licence), (X $_.copyright)) })
    $null = $sb.AppendLine('    <section id="fonts">')
    $null = $sb.AppendLine('      <title>Fonts</title>')
    $null = $sb.AppendLine('      <p>These are the fonts that uFTi shows its words and symbols in.</p>')
    $null = $sb.AppendLine((Table 'Fonts in uFTi' @('Font', 'Licence', 'Copyright') $rows))
    $null = $sb.AppendLine('    </section>')

    # content
    foreach ($c in $j.content) {
        $null = $sb.AppendLine('    <section id="sample-tree">')
        $null = $sb.AppendLine('      <title>The sample tree</title>')
        $null = $sb.AppendLine('      <p>' + (X $c.name) + '. ' + (X $c.copyright) + '. It was researched for uFTi from published sources that it cites.</p>')
        $media = @($c.media)
        if ($media.Count -gt 0) {
            $null = $sb.AppendLine('      <p>The pictures are not part of uFTi. The sample tree links to them on Wikimedia Commons.</p>')
            $rows = @($media | ForEach-Object { Row @((Link $_.url $_.title), (X $_.note)) })
            $null = $sb.AppendLine((Table 'Pictures that the sample tree links to' @('Picture', 'Licence and source') $rows))
        }
        $null = $sb.AppendLine('    </section>')
    }

    # words
    $null = $sb.AppendLine('    <section id="words-we-use">')
    $null = $sb.AppendLine('      <title>Words we use</title>')
    $null = $sb.AppendLine('      <dl>')
    $words = @(
        @('Copyright', 'The right of the person who made something to say what may be done with it.'),
        @('Library', 'A part of a program that someone else wrote and that other programs use.'),
        @('Licence', 'The permission that the maker of something gives you to use it, and the rules that come with it.'),
        @('Licence name', 'The short name of a licence, such as MIT or Apache-2.0. The names come from a public list that many programs use.')
    )
    foreach ($w in $words) {
        $null = $sb.AppendLine('        <dlentry>')
        $null = $sb.AppendLine('          <dt>' + (X $w[0]) + '</dt>')
        $null = $sb.AppendLine('          <dd>' + (X $w[1]) + '</dd>')
        $null = $sb.AppendLine('        </dlentry>')
    }
    $null = $sb.AppendLine('      </dl>')
    $null = $sb.AppendLine('    </section>')
    $null = $sb.AppendLine('  </refbody>')
    $null = $sb.AppendLine('</reference>')
    return ($sb.ToString() -replace "`r`n", "`n")
}

$differ = 0
foreach ($t in $targets) {
    $src = Join-Path $Data "$($t.Data).json"
    if (-not (Test-Path -LiteralPath $src)) { throw "No inventory data at $src (run import-components.ps1)" }
    $j = [System.IO.File]::ReadAllText($src, [System.Text.Encoding]::UTF8) | ConvertFrom-Json -Depth 20
    $text = New-Topic $j $t.Device
    $dest = Join-Path $Root "$($t.Folder)/topics/software-components.dita"
    if ($Check) {
        $have = if (Test-Path -LiteralPath $dest) { ([System.IO.File]::ReadAllText($dest, [System.Text.Encoding]::UTF8) -replace "`r`n", "`n") } else { $null }
        if ($have -ne $text) { Write-Host "FAIL: $($t.Folder)/topics/software-components.dita does not match content/components/$($t.Data).json: run build/scripts/new-components-topics.ps1"; $differ++ }
    }
    else {
        New-Item -ItemType Directory -Force -Path (Split-Path $dest) | Out-Null
        [System.IO.File]::WriteAllText($dest, $text, [System.Text.UTF8Encoding]::new($false))
        Write-Host ("wrote {0}" -f $dest.Substring($repo.Length + 1))
    }
}
if ($Check) { if ($differ) { exit 1 } else { Write-Host 'PASS: the components topics match their data.' } }
